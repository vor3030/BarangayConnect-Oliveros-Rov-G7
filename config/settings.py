POSTGRES_CONN_MAX_AGE = int(os.getenv("POSTGRES_CONN_MAX_AGE", "0"))
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
if DATABASE_URL:
    _ssl_mode = os.getenv("POSTGRES_SSLMODE", "").strip().lower()
    _ssl_require = (
        _ssl_mode not in {"disable", "allow", "prefer"} if _ssl_mode else not DEBUG
    )
    DATABASES = {
        "default": dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=POSTGRES_CONN_MAX_AGE,
            ssl_require=_ssl_require,
        )
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.getenv("POSTGRES_DB", "barangay_connect"),
            "USER": os.getenv("POSTGRES_USER", "barangay_connect"),
            "PASSWORD": os.getenv("POSTGRES_PASSWORD", ""),
            "HOST": os.getenv("POSTGRES_HOST", "127.0.0.1"),
            "PORT": os.getenv("POSTGRES_PORT", "5432"),
            "CONN_MAX_AGE": POSTGRES_CONN_MAX_AGE,
            "OPTIONS": {"sslmode": os.getenv("POSTGRES_SSLMODE", "prefer")},
        }
    }

